/// Labelled ground truth review evaluation fixture.
#[derive(Debug, Clone, Deserialize)]
#[allow(dead_code)]
struct EvalFixture {
    id: String,
    name: String,
    description: String,
    diff: String,
    expected_type: String, // "true_positive", "false_positive_trap", "intent_violation"
    #[serde(default)]
    expected_file: String,
    #[serde(default)]
    expected_category: Option<String>,
    #[serde(default)]
    expected_min_severity: Option<String>,
    #[serde(default)]
    expected_dismissal: bool,
    #[serde(default)]
    intent: Option<PrMetadata>,
    #[serde(default)]
    detective_response: Option<String>,
    #[serde(default)]
    judge_response: Option<String>,
}

/// Recorded replay provider that responds deterministically to Detective and Judge prompts without network or token costs.
struct ReplayProvider {
    fixture: EvalFixture,
    calls: Arc<Mutex<Vec<String>>>,
}

impl ReplayProvider {
    /// Constructs a deterministic replay provider for the specified fixture.
    fn new(fixture: EvalFixture) -> Self {
        Self {
            fixture,
            calls: Arc::new(Mutex::new(Vec::new())),
        }
    }
}

#[async_trait]
impl Provider for ReplayProvider {
    /// Returns the provider name identifier.
    fn name(&self) -> &str {
        "ReplayProvider"
    }

    /// Dispatches prompt completion to mock responses based on Pass 1 detective or Pass 2 judge prompt signatures.
    async fn complete(&self, prompt: &str) -> Result<String> {
        let mut calls = self.calls.lock().await;
        // Pass 1 prompt generated by `revue::reviewer::generate_pass1_detective_prompt`
        if prompt.contains("PASS 1: Broad Defect Discovery") {
            calls.push("detective".to_string());
            if let Some(ref resp) = self.fixture.detective_response {
                return Ok(resp.clone());
            }
            return Ok(format!(
                "- In `{}`: Potential anomaly detected according to fixture rules.",
                self.fixture.expected_file
            ));
        }

        // Pass 2 prompt generated by `revue::reviewer::generate_pass2_judge_prompt`
        if prompt.contains("OUTPUT FORMAT:") || prompt.contains("VERIFICATION GUIDELINES:") {
            calls.push("judge".to_string());
            if let Some(ref resp) = self.fixture.judge_response {
                return Ok(resp.clone());
            }
            if self.fixture.expected_dismissal {
                return Ok("```json\n{\n  \"summary\": \"Verified and dismissed harmless pattern.\",\n  \"issues\": []\n}\n```".to_string());
            }
            return Ok(format!(
                r#"```json
{{
  "summary": "Verified issue in {}",
  "issues": [
    {{
      "file": "{}",
      "line": 1,
      "severity": "{}",
      "title": "{}",
      "comment": "{}",
      "confidence": 9
    }}
  ]
}}
```"#,
                self.fixture.expected_file,
                self.fixture.expected_file,
                self.fixture
                    .expected_min_severity
                    .as_deref()
                    .unwrap_or("warning"),
                self.fixture.name,
                self.fixture.description,
            ));
        }

        // Single pass default
        calls.push("single_pass".to_string());
        Ok(r#"{"summary": "No issues", "issues": []}"#.to_string())
    }
}

/// Verifies that all ground-truth fixtures in `tests/fixtures/eval/` parse and validate against diff structure.
#[test]
fn test_eval_benchmark_fixtures_load_and_parse() {
    let fixtures_dir = Path::new("tests/fixtures/eval");
    assert!(fixtures_dir.exists(), "eval fixtures directory must exist");

    let entries = fs::read_dir(fixtures_dir).expect("failed to read fixtures directory");
    let mut count = 0;

    for entry in entries {
        let entry = entry.expect("valid directory entry");
        let path = entry.path();
        if path.extension().and_then(|s| s.to_str()) == Some("json") {
            let content = fs::read_to_string(&path).expect("readable fixture file");
            let fixture: EvalFixture =
                serde_json::from_str(&content).expect("valid fixture JSON schema");

            assert!(!fixture.id.is_empty());
            assert!(!fixture.name.is_empty());
            assert!(!fixture.diff.is_empty());

            let parsed = ParsedDiff::parse(&fixture.diff).expect("diff must parse cleanly");
            assert!(
                !parsed.files.is_empty(),
                "parsed files should not be empty for {}",
                fixture.id
            );

            if !fixture.expected_file.is_empty() {
                assert!(
                    parsed
                        .files
                        .iter()
                        .any(|f| f.new_path == fixture.expected_file),
                    "fixture {} expected file {} in diff",
                    fixture.id,
                    fixture.expected_file
                );
            }

            count += 1;
        }
    }

    assert!(
        count >= 5,
        "expected at least 5 benchmark fixtures, found {}",
        count
    );
}

/// Runs the deterministic offline replay benchmark measuring recall, trap rejection, and precision.
#[tokio::test]
async fn test_eval_benchmark_pipeline_replay_scorecard() {
    let fixtures_dir = Path::new("tests/fixtures/eval");
    let mut entries: Vec<_> = fs::read_dir(fixtures_dir)
        .expect("readable fixtures dir")
        .filter_map(|e| e.ok())
        .filter(|e| e.path().extension().and_then(|s| s.to_str()) == Some("json"))
        .collect();
    entries.sort_by_key(|e| e.path());

    let mut total_true_positives = 0;
    let mut detected_true_positives = 0;
    let mut total_traps = 0;
    let mut rejected_traps = 0;
    let mut total_verified_findings = 0;

    println!("\n======================= REVUE EVALUATION HARNESS =======================");
    println!("Executing offline deterministic replay benchmark (0 tokens consumed)...\n");

    for entry in entries {
        let content = fs::read_to_string(entry.path()).expect("readable fixture");
        let fixture: EvalFixture = serde_json::from_str(&content).expect("valid fixture");

        let diff = ParsedDiff::parse(&fixture.diff).expect("parseable diff");
        let mut config = RevueConfig::default();
        config.review.semgrep = false; // Isolated LLM cascade testing
        config.review.two_pass = true;

        let replay = Box::new(ReplayProvider::new(fixture.clone()));
        let chain = ProviderChain::new(vec![replay]);

        let result = execute_review_pipeline(
            &diff,
            &config,
            &chain,
            &[],
            None,
            None,
            fixture.intent.as_ref(),
            &[],
        )
        .await
        .expect("pipeline execution succeeded");

        let is_trap = fixture.expected_type == "false_positive_trap" || fixture.expected_dismissal;
        let findings_on_target = result
            .issues
            .iter()
            .filter(|i| i.file == fixture.expected_file)
            .count();

        total_verified_findings += result.issues.len();

        if is_trap {
            total_traps += 1;
            let dismissed = findings_on_target == 0;
            if dismissed {
                rejected_traps += 1;
                println!(
                    "  ✔ [TRAP DISMISSED]  {:<35} -> 0 issues (correctly suppressed)",
                    fixture.id
                );
            } else {
                println!(
                    "  ❌ [TRAP LEAKED]     {:<35} -> {} issues flagged (false positive!)",
                    fixture.id, findings_on_target
                );
            }
        } else {
            total_true_positives += 1;
            let caught = findings_on_target > 0;
            if caught {
                detected_true_positives += 1;
                let top_issue = &result.issues[0];
                println!(
                    "  ✔ [BUG CAUGHT]      {:<35} -> {} (conf: {})",
                    fixture.id,
                    top_issue.title,
                    top_issue.confidence.unwrap_or(0)
                );
            } else {
                println!(
                    "  ❌ [BUG MISSED]      {:<35} -> 0 findings on target file",
                    fixture.id
                );
            }
        }
    }

    let recall = if total_true_positives > 0 {
        (detected_true_positives as f64 / total_true_positives as f64) * 100.0
    } else {
        100.0
    };

    let trap_rejection = if total_traps > 0 {
        (rejected_traps as f64 / total_traps as f64) * 100.0
    } else {
        100.0
    };

    let precision = if total_verified_findings > 0 {
        (detected_true_positives as f64 / total_verified_findings as f64) * 100.0
    } else {
        100.0
    };

    println!("\n----------------------- EVALUATION SCORECARD -----------------------");
    println!("  True Positive Bugs Evaluated:  {}", total_true_positives);
    println!("  False-Positive Traps Tested:   {}", total_traps);
    println!(
        "  Recall (Bug Detection):        {:.1}% ({}/{})",
        recall, detected_true_positives, total_true_positives
    );
    println!(
        "  Trap Rejection (Adversarial):  {:.1}% ({}/{})",
        trap_rejection, rejected_traps, total_traps
    );
    println!("  Precision:                     {:.1}%", precision);
    println!("  Token Cost:                    $0.00 (Deterministic Replay)");
    println!("====================================================================\n");

    assert_eq!(recall, 100.0, "Recall must be 100% on replay benchmark");
    assert_eq!(
        trap_rejection, 100.0,
        "Trap rejection must be 100% on replay benchmark"
    );
}

/// Live Ollama evaluation test against local fleet GPU.
/// Run on-demand via `cargo test --test eval_benchmark -- test_eval_live_ollama_benchmark --nocapture --ignored`
/// or `just eval-local`.
#[tokio::test]
#[ignore]
async fn test_eval_live_ollama_benchmark() {
    let endpoint =
        std::env::var("OLLAMA_URL").unwrap_or_else(|_| "http://127.0.0.1:11434".to_string());
    let model = std::env::var("OLLAMA_MODEL").unwrap_or_else(|_| "qwen2.5-coder:14b".to_string());

    println!(
        "Testing connectivity to local Ollama at {} (model: {})...",
        endpoint, model
    );
    let client = reqwest::Client::builder()
        .timeout(std::time::Duration::from_secs(3))
        .build()
        .unwrap();

    let health_url = format!("{}/api/tags", endpoint);
    let health_check = match client.get(&health_url).send().await {
        Ok(resp) => resp.error_for_status(),
        Err(e) => {
            println!(
                "  [SKIPPED] Local Ollama is unreachable at {}: {}. Skipping live benchmark cleanly.",
                endpoint, e
            );
            return;
        }
    };
    if let Err(e) = health_check {
        println!(
            "  [SKIPPED] Local Ollama returned non-success status at {}: {}. Skipping live benchmark cleanly.",
            endpoint, e
        );
        return;
    }

    println!("Connected to local Ollama! Running live evaluation benchmark without token cost...");
    let fixtures_dir = Path::new("tests/fixtures/eval");
    let mut entries: Vec<_> = fs::read_dir(fixtures_dir)
        .expect("readable fixtures dir")
        .filter_map(|e| e.ok())
        .filter(|e| e.path().extension().and_then(|s| s.to_str()) == Some("json"))
        .collect();
    entries.sort_by_key(|e| e.path());

    let mut true_positives = 0;
    let mut caught = 0;
    let mut traps = 0;
    let mut rejected = 0;
    let mut inference_errors = 0;

    for entry in entries {
        let content = fs::read_to_string(entry.path()).expect("readable fixture");
        let fixture: EvalFixture = serde_json::from_str(&content).expect("valid fixture");

        let diff = ParsedDiff::parse(&fixture.diff).expect("parseable diff");
        let mut config = RevueConfig::default();
        config.review.two_pass = true;
        config.review.semgrep = false;

        let provider = Box::new(
            revue::providers::openai_compat::OpenAiCompatProvider::ollama(
                endpoint.clone(),
                model.clone(),
            ),
        );
        let chain = ProviderChain::new(vec![provider]);

        match execute_review_pipeline(
            &diff,
            &config,
            &chain,
            &[],
            None,
            None,
            fixture.intent.as_ref(),
            &[],
        )
        .await
        {
            Ok(res) => {
                let is_trap =
                    fixture.expected_type == "false_positive_trap" || fixture.expected_dismissal;
                let target_issues = res
                    .issues
                    .iter()
                    .filter(|i| i.file == fixture.expected_file)
                    .count();
                if is_trap {
                    traps += 1;
                    if target_issues == 0 {
                        rejected += 1;
                        println!("  ✔ [LIVE TRAP DISMISSED] {:<30}", fixture.id);
                    } else {
                        println!(
                            "  ❌ [LIVE TRAP LEAKED]    {:<30} ({} issues)",
                            fixture.id, target_issues
                        );
                    }
                } else {
                    true_positives += 1;
                    if target_issues > 0 {
                        caught += 1;
                        println!("  ✔ [LIVE BUG CAUGHT]     {:<30}", fixture.id);
                    } else {
                        println!("  ❌ [LIVE BUG MISSED]     {:<30}", fixture.id);
                    }
                }
            }
            Err(e) => {
                inference_errors += 1;
                println!(
                    "  ⚠️ [ERROR] Live inference failed for {}: {}",
                    fixture.id, e
                );
            }
        }
    }

    println!(
        "\nLive Ollama Evaluation completed. Bugs caught: {}/{}, Traps rejected: {}/{}, Errors: {}",
        caught, true_positives, rejected, traps, inference_errors
    );
    assert_eq!(
        inference_errors, 0,
        "Expected 0 live inference errors, but encountered {}",
        inference_errors
    );
}
