export type CanonicalSeverity =
	| 'security'
	| 'critical'
	| 'bug'
	| 'error'
	| 'performance'
	| 'warning'
	| 'info';

export type SeverityBucket = 'critical' | 'major' | 'minor';

export interface RawApiFinding {
	file?: string;
	line?: number;
	severity?: string;
	title?: string;
	body?: string;
	comment?: string;
	confidence?: number;
	snippet?: string;
	suggestion?: string;
	category?: string;
	committable_patch?: string;
	feedback?: string;
}

export interface NormalizedFinding {
	file: string;
	line: number;
	severity: CanonicalSeverity;
	title: string;
	body: string;
	confidence?: number;
	snippet?: string;
	category?: string;
	committable_patch?: string;
	feedback?: string;
}

export interface WizardYamlOptions {
	min_severity: 'info' | 'warning' | 'error' | 'critical';
	summary?: boolean;
	two_pass: boolean;
	semgrep: boolean;
	ignore_lockfiles: boolean;
	ignore_vendor: boolean;
	ignore_generated: boolean;
	tone: string;
	custom_guidelines: string;
}

const KNOWN_SEVERITIES = new Set<CanonicalSeverity>([
	'security',
	'critical',
	'bug',
	'error',
	'performance',
	'warning',
	'info'
]);

export function normalizeSeverity(raw?: string | null): CanonicalSeverity {
	const lowered = (raw ?? '').trim().toLowerCase() as CanonicalSeverity;
	return KNOWN_SEVERITIES.has(lowered) ? lowered : 'warning';
}

export function severityBucket(severity: string): SeverityBucket {
	switch (normalizeSeverity(severity)) {
		case 'security':
		case 'critical':
			return 'critical';
		case 'bug':
		case 'error':
			return 'major';
		case 'performance':
		case 'warning':
		case 'info':
			return 'minor';
	}
}

export function mapApiFinding(raw: RawApiFinding): NormalizedFinding {
	return {
		file: raw.file || 'unknown',
		line: typeof raw.line === 'number' && Number.isFinite(raw.line) ? raw.line : 1,
		severity: normalizeSeverity(raw.severity),
		title: raw.title || 'Finding',
		body: raw.body || raw.comment || '',
		confidence: raw.confidence,
		snippet: raw.snippet || raw.suggestion,
		category: raw.category,
		committable_patch: raw.committable_patch,
		feedback: raw.feedback
	};
}

export function computeNoiseReductionPct(
	pass1Candidates: number,
	verifiedFindings: number
): number | null {
	if (!Number.isFinite(pass1Candidates) || pass1Candidates <= 0) {
		return null;
	}
	const clampedVerified = Math.max(0, Math.min(pass1Candidates, verifiedFindings));
	return Math.round(((pass1Candidates - clampedVerified) / pass1Candidates) * 100);
}

export function generateRevueYaml(opts: WizardYamlOptions): string {
	const ignores: string[] = [];
	if (opts.ignore_lockfiles) {
		ignores.push('**/flake.lock', '**/Cargo.lock', '**/package-lock.json', '**/pnpm-lock.yaml');
	}
	if (opts.ignore_vendor) {
		ignores.push('**/vendor/**', '**/node_modules/**', 'third_party/**');
	}
	if (opts.ignore_generated) {
		ignores.push('**/*.min.js', '**/*.pb.go', '**/dist/**', '**/build/**', 'target/**');
	}

	const lines: string[] = [
		'# Generated by Revue Configuration Wizard',
		'version: 1',
		'',
		'review:',
		'  language: en-GB',
		`  tone: ${JSON.stringify(opts.tone.trim() || 'Short and direct. Lead with the problem and the fix.')}`,
		`  summary: ${opts.summary ?? true}`,
		`  two_pass: ${opts.two_pass}`,
		`  semgrep: ${opts.semgrep}`,
		`  min_severity: ${opts.min_severity}`
	];

	if (ignores.length > 0) {
		lines.push('', '  ignore:');
		for (const pattern of ignores) {
			lines.push(`    - ${JSON.stringify(pattern)}`);
		}
	}

	const trimmedGuidelines = opts.custom_guidelines.trim();
	if (trimmedGuidelines.length > 0) {
		lines.push('', '  rules:', '    - path: "**"', '      instructions: |');
		for (const guidelineLine of trimmedGuidelines.split(/\r?\n/)) {
			lines.push(`        ${guidelineLine}`);
		}
	}

	return `${lines.join('\n')}\n`;
}
